"""Derive `configs/pusht_dino_p256_td_k{K}.yaml` for K in {5, 10, 40}.

The sweep's claim is "the anchor count is the ONLY thing that differs". A claim like
that is worth exactly as much as the diff that demonstrates it, so these files are
GENERATED by substitution from the K=20 config rather than hand-written: the diff
between any two of them is then provably the two lines below and nothing else.

Two lines change, because K appears in exactly two places:
  * `td.n_modes`         -- the bin_head's output width (number of modes)
  * `td.anchor_artifact` -- which k-means artifact the head loads

Everything else is copied verbatim, INCLUDING `td.infer_t_start: 49`. All four K values
independently recommend t_start=49 (see scripts/report_k_sweep.py), so holding it fixed
is not a compromise -- it is each arm's own measured recommendation.

Usage (from the repo root):
    python scripts/make_k_configs.py [--base configs/pusht_dino_p256_td.yaml]
"""
import argparse
from pathlib import Path

KS = (5, 10, 40)
BASE = "configs/pusht_dino_p256_td.yaml"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default=BASE)
    args = ap.parse_args()

    base_path = Path(args.base)
    text = base_path.read_text(encoding="utf-8")

    # Anchor the substitutions to the exact expected lines so a rename in the base file
    # fails loudly here instead of silently producing a config that trains K=20.
    assert text.count("  n_modes: 20") == 1, "base has no unique `  n_modes: 20` line"
    assert text.count("  anchor_artifact: anchors/pusht_kmeans_K20.pt") == 1, \
        "base has no unique `  anchor_artifact: anchors/pusht_kmeans_K20.pt` line"

    header = (
        "# GENERATED by scripts/make_k_configs.py -- do not hand-edit.\n"
        "# Anchor-count sweep: this file differs from {b} in EXACTLY two lines,\n"
        "# `td.n_modes` and `td.anchor_artifact`. Verify with:\n"
        "#   diff configs/pusht_dino_p256_td_k5.yaml configs/pusht_dino_p256_td_k40.yaml\n"
    ).format(b=base_path.name)

    for k in KS:
        out = text.replace("  n_modes: 20", "  n_modes: %d" % k)
        out = out.replace("  anchor_artifact: anchors/pusht_kmeans_K20.pt",
                          "  anchor_artifact: anchors/pusht_kmeans_K%d.pt" % k)
        dst = base_path.parent / ("pusht_dino_p256_td_k%d.yaml" % k)
        # newline="\n" explicitly: the base config is CRLF (it was authored on Windows),
        # and inheriting that would leave a stray \r on every line. YAML does not care,
        # but shell `grep '...$'` does -- the driver's sanity guard silently stopped
        # matching, which is exactly the class of failure that guard exists to catch.
        with open(dst, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(header + out)
        print("[cfg] wrote %s (LF)" % dst)


if __name__ == "__main__":
    main()
